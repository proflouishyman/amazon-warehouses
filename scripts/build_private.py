def unify(fname, spec):
    out = []
    for r in rd(os.path.join(P, fname)):
        oc = spec.get('only_category')
        if oc:
            is_pull = (r.get('category') or '').lower() == 'pullback'
            if (oc == 'pullback') != is_pull:
                continue
        def g(field, default_keys):
            keys = spec.get(field, default_keys)
            return first(r, *keys) if keys else ''
        quote = g('quote', [])
        if spec.get('extra_count') and r.get('count'):
            quote = (quote + ' (count %s)' % r['count']).strip()
        if spec.get('value') and r.get('value'):
            quote = ('%s %s %s; %s' % (r.get('metric', ''), r.get('value', ''), r.get('unit', ''), quote)).strip()
        out.append(dict(
            source=slug(fname), publication=r.get('publication', ''), article_date=iso(first(r, *(spec.get('article_date') or ['article_date']))),
            event_date=g('event_date', []), event=g('event', []),
            city=g('city', ['city']), state=g('state', ['state']), facility_type=g('facility_type', ['facility_type']),
            sq_ft=g('sq_ft', ['sq_ft']), title=r.get('title', ''), database=r.get('database', ''), quote=quote[:600], url=g('url', [])))
    return out


