def rd(path):
    if not os.path.isabs(path):
        path = os.path.join(ROOT, path)
    with open(path, newline='', encoding='utf-8') as fh:
        return list(csv.DictReader(fh))


def tab(rows, cols):
    return {'cols': cols, 'rows': [[(r.get(c) if r.get(c) not in ('', None) else None) for c in cols] for r in rows]}


def write(fname, glob_name, obj):
    path = os.path.join(A, fname)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('/* LOCAL ONLY: generated by scripts/build_private.py on %s. Gitignored. Never publish. */\nwindow.%s=' % (STAMP, glob_name))
        json.dump(obj, fh, separators=(',', ':'), ensure_ascii=False)
        fh.write(';\n')
    SIZES.append((fname, glob_name, os.path.getsize(path)))


def first(r, *keys):
    for k in keys:
        v = (r.get(k) or '').strip()
        if v:
            return v
    return ''


def iso(d):
    """Normalise article dates (01/04/2017, July 31, 2023) to ISO for sorting; anything else is left as is."""
    d = (d or '').strip()
    for f in ('%m/%d/%Y', '%B %d, %Y', '%b %d, %Y'):
        try:
            return datetime.datetime.strptime(d, f).strftime('%Y-%m-%d')
        except ValueError:
            pass
    return d


def slug(path):
    return re.sub(r'^jhu_|\.csv$', '', os.path.basename(path))


