def md_inline(s):
    s = html.escape(s)
    s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', s)
    s = re.sub(r'(?<![\w*])\*([^*\s][^*]*)\*(?!\w)', r'<i>\1</i>', s)
    s = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', lambda m: '<a href="%s">%s</a>' % (m.group(2), m.group(1)), s)
    return s


def md_render(text):
    out, lines, i, inlist, para = [], text.split('\n'), 0, False, []
    def flush():
        nonlocal para
        if para:
            out.append('<p>' + md_inline(' '.join(para)) + '</p>')
            para = []
    def closelist():
        nonlocal inlist
        if inlist:
            out.append('</ul>')
            inlist = False
    while i < len(lines):
        ln = lines[i]
        m = re.match(r'^(#{1,6})\s+(.*)', ln)
        if m:
            flush(); closelist()
            n = min(6, len(m.group(1)) + 1)
            out.append('<h%d>%s</h%d>' % (n, md_inline(m.group(2)), n))
        elif ln.startswith('|') and i + 1 < len(lines) and re.match(r'^\|[\s:|-]+\|?\s*$', lines[i + 1]):
            flush(); closelist()
            hdr = [c.strip() for c in ln.strip().strip('|').split('|')]
            i += 2
            body = []
            while i < len(lines) and lines[i].startswith('|'):
                body.append([c.strip() for c in lines[i].strip().strip('|').split('|')])
                i += 1
            i -= 1
            out.append('<div class="tw"><table><thead><tr>' + ''.join('<th>%s</th>' % md_inline(c) for c in hdr) + '</tr></thead><tbody>' +
                       ''.join('<tr>' + ''.join('<td>%s</td>' % md_inline(c) for c in row) + '</tr>' for row in body) + '</tbody></table></div>')
        elif re.match(r'^\s*[-*]\s+', ln):
            flush()
            if not inlist:
                out.append('<ul>')
                inlist = True
            out.append('<li>' + md_inline(re.sub(r'^\s*[-*]\s+', '', ln)) + '</li>')
        elif re.match(r'^\s*\d+\.\s+', ln):
            flush(); closelist()
            out.append('<p>' + md_inline(ln.strip()) + '</p>')
        elif not ln.strip():
            flush(); closelist()
        else:
            closelist()
            para.append(ln.strip())
        i += 1
    flush(); closelist()
    return '\n'.join(out)


