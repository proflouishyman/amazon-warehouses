def read_shp(base):
    shp = open(base + '.shp', 'rb').read()
    dbf = open(base + '.dbf', 'rb').read()
    nrec, hlen, rlen = struct.unpack('<xxxxIHH', dbf[:12])
    fields, off = [], 32
    while dbf[off] != 0x0D:
        fields.append((dbf[off:off + 11].split(b'\0')[0].decode(), dbf[off + 16]))
        off += 32
    attrs = []
    for i in range(nrec):
        rec = dbf[hlen + i * rlen: hlen + (i + 1) * rlen][1:]
        d, o = {}, 0
        for n, ln in fields:
            d[n] = rec[o:o + ln].decode('latin-1').strip()
            o += ln
        attrs.append(d)
    out, pos, i = [], 100, 0
    while pos < len(shp):
        _, clen = struct.unpack('>ii', shp[pos:pos + 8])
        body = shp[pos + 8: pos + 8 + clen * 2]
        pos += 8 + clen * 2
        st = struct.unpack('<i', body[:4])[0]
        if st == 5:
            npart, npts = struct.unpack('<ii', body[36:44])
            parts = list(struct.unpack('<%di' % npart, body[44:44 + 4 * npart])) + [npts]
            pts = struct.unpack('<%dd' % (2 * npts), body[44 + 4 * npart:44 + 4 * npart + 16 * npts])
            rings = [[(pts[2 * j], pts[2 * j + 1]) for j in range(parts[k], parts[k + 1])] for k in range(npart)]
            out.append((attrs[i], rings))
        i += 1
    return out


def albers(lat0, lon0, lat1, lat2):
    p = math.pi / 180
    n = (math.sin(lat1 * p) + math.sin(lat2 * p)) / 2
    C = math.cos(lat1 * p) ** 2 + 2 * n * math.sin(lat1 * p)
    r0 = math.sqrt(C - 2 * n * math.sin(lat0 * p)) / n

    def f(lat, lon):
        r = math.sqrt(C - 2 * n * math.sin(lat * p)) / n
        th = n * (lon - lon0) * p
        return r * math.sin(th), r0 - r * math.cos(th)
    return f


