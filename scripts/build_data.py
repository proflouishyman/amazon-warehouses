# ------------------------------------------------------------------ public-safety guard for tables built from subscription-derived files
PROXY_RE = re.compile(r'ezproxy|\.proxy\.|login\.proxy|proquest\.com/docview|proquest\.com/openview|jhu\.idm', re.I)
QUOTE_RE = re.compile(r'"([^"]{20,})"|“([^”]{20,})”')
guard_log = []


def guard(name, rows, skip_cols=()):
    """Fail the build if a published table holds a proxy URL or a quotation longer than 15 words (subscription-material rule)."""
    for i, r in enumerate(rows):
        for k, v in r.items():
            if k in skip_cols or not v:
                continue
            if PROXY_RE.search(v):
                raise SystemExit('GUARD %s row %d col %s: proxy URL' % (name, i, k))
            for m in QUOTE_RE.finditer(v):
                q = m.group(1) or m.group(2)
                if len(q.split()) > 15:
                    raise SystemExit('GUARD %s row %d col %s: quotation of %d words' % (name, i, k, len(q.split())))
    guard_log.append(name)
    return rows


def compact(rows, drop=(), const_min_len=100):
    """Drop `drop` columns; move long text columns with at most 3 distinct values into a constants dict (repeated source strings)."""
    cols = [c for c in rows[0] if c not in drop]
    consts = {}
    for c in list(cols):
        vals = {r[c] for r in rows if r[c]}
        if 0 < len(vals) <= 3 and sum(len(v) for v in vals) / len(vals) > const_min_len:
            consts[c] = sorted(vals)
            cols.remove(c)
    return cols, consts


