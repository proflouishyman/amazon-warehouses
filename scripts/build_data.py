def xy(lat, lon):
    """Screen coordinates in a 960 x 600 viewBox (AK and HI are insets, like d3 geoAlbersUsa but simplified)."""
    r, (x, y) = _raw(lat, lon)
    if r == 'US':
        return 10 + (x - minx) * K, 10 + (maxy - y) * K * 1.0
    sc, cx, cy, tg = ins[r]
    return tg[0] + (x - cx) * K * sc, tg[1] - (y - cy) * K * sc


def path_of(rings):
    d = []
    for ring in rings:
        pts = [xy(lat, lon) for lon, lat in ring]
        # thin points closer than 0.4 px
        out = [pts[0]]
        for p in pts[1:]:
            if abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) >= 0.4:
                out.append(p)
        if len(out) >= 3:
            d.append('M' + 'L'.join('%.1f,%.1f' % p for p in out) + 'Z')
    return ''.join(d)


