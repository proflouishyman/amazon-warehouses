def conv(col_vals):
    """Return a converter for a column: numeric if every non-empty value is numeric and none has a leading zero."""
    vals = [str(v) for v in col_vals if v not in ('', None)]
    if not vals:
        return lambda v: None
    ok = True
    for v in vals:
        try:
            float(v)
        except ValueError:
            ok = False
            break
        if re.match(r'^[+-]?0\d', v):
            ok = False
            break
    if not ok:
        return lambda v: None if v in ('', None) else v
    allint = all(re.match(r'^[+-]?\d+$', v) for v in vals)

    def f(v):
        if v in ('', None):
            return None
        x = float(v)
        return int(x) if allint else (round(x, 6) if abs(x) < 1e12 else x)
    return f


def table(rows, cols=None, drop=(), keep=None):
    cols = cols or [c for c in rows[0] if c not in drop]
    if keep:
        cols = [c for c in cols if c in keep]
    cv = {c: conv([r.get(c) for r in rows]) for c in cols}
    return {'cols': cols, 'rows': [[cv[c](None if r.get(c) in ('', None) else str(r.get(c))) for c in cols] for r in rows]}


def write_js(fname, glob, obj):
    path = os.path.join(A, fname)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('/* generated by scripts/build_data.py on %s - do not edit */\nwindow.%s=' % (GENERATED, glob))
        json.dump(obj, fh, separators=(',', ':'), ensure_ascii=False)
        fh.write(';\n')
    for k, v in obj.items():
        if isinstance(v, dict) and 'cols' in v:
            dictionary.append((glob, k, v['cols'], len(v['rows'])))
        else:
            dictionary.append((glob, k, [], len(v) if hasattr(v, '__len__') else 1))
    print('%-22s %-18s %8.0f KB' % (fname, glob, os.path.getsize(path) / 1024))


