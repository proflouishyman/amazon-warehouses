"""Public source list: data/sources_manifest_public.csv and a scrubbed data/SOURCES.md.

Run:  python3 -I scripts/build_sources_public.py     (after scripts/build_sources_manifest.py has written data/sources_manifest.csv)

- sources_manifest_public.csv = the rows of the local data/sources_manifest.csv with access = public, same columns.
  In used_by, references to subscription extracts, data/private and local-only files are removed.
- data/SOURCES.md is regenerated by scripts/gen_sources_md.py, then its manifest link and subscription sentences are pointed at the public manifest,
  and the build fails if the text mentions a local machine path or user name.
data/sources_manifest.csv itself is gitignored (it lists subscription documents).
"""
import csv, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'data')
SRC, OUT, MD = [os.path.join(D, x) for x in ('sources_manifest.csv', 'sources_manifest_public.csv', 'SOURCES.md')]
PRIVATE_TOKEN = re.compile(r'data/private|jhu_|statista|LOGBOOK|sources_manifest\.csv', re.I)
LOCAL = re.compile(r'[/]Users/|louishyman|lhyman|ces-server|C:\\\\Users', re.I)

with open(SRC, newline='', encoding='utf-8') as fh:
    rd = csv.DictReader(fh)
    cols = rd.fieldnames
    rows = list(rd)
pub = [r for r in rows if r['access'] == 'public']
for r in pub:
    r['used_by'] = ' | '.join(t for t in r['used_by'].split(' | ') if t and not PRIVATE_TOKEN.search(t))
    for k, v in r.items():
        if LOCAL.search(v or ''):
            raise SystemExit('public manifest: local path or user name in %s: %s' % (k, v[:100]))
with open(OUT, 'w', newline='', encoding='utf-8') as fh:
    w = csv.DictWriter(fh, fieldnames=cols)
    w.writeheader()
    w.writerows(pub)
print('public manifest: %d of %d rows' % (len(pub), len(rows)))

subprocess.run([sys.executable, '-I', os.path.join(ROOT, 'scripts/gen_sources_md.py')], check=True)
t = open(MD, encoding='utf-8').read()
t = re.sub(r'Every file under `data/raw` and `data/private` is catalogued in \[`sources_manifest\.csv`\]\(sources_manifest\.csv\), one row per file \(([\d,]+) files, ([\d.]+ GB)\)\.',
           lambda m: 'Every file under `data/raw` and `data/private` is catalogued in a local manifest (%s files, %s). The public-access files are listed one row per file in '
                     '[`sources_manifest_public.csv`](sources_manifest_public.csv) (%s rows); subscription files are counted here but not listed.' % (m.group(1), m.group(2), format(len(pub), ',')), t)
t = t.replace('This guide and the manifest are the public record of what exists.', 'This guide and the public manifest are the public record of the public sources.')
t = re.sub(r'The manifest lists only title, publication, date, a document id or link, and counts for these rows\. Facts that came from them live in `data/processed/jhu_\*\.csv`, which should be reviewed before any public release\.',
           'This guide gives counts only for these rows. Facts drawn from them appear on the pages cited as publication, date, title (via database), with no long quotations and no proxy links; '
           'the citations are listed in `data/processed/bibliography_subscription.csv`.', t)
t = re.sub(r'[/]Users/[A-Za-z0-9_.-]+/', '~/', t)
t = t.replace('`python3 scripts/build_sources_manifest.py` rewrites the manifest', '`python3 scripts/build_sources_manifest.py` rewrites the local manifest').replace(
    '`python3 scripts/gen_sources_md.py` rewrites this file from it.', '`python3 scripts/build_sources_public.py` writes the public manifest and rewrites this file from it.')
bad = LOCAL.findall(t)
if bad:
    raise SystemExit('SOURCES.md still mentions a local path or user name: %s' % bad[:3])
open(MD, 'w', encoding='utf-8').write(t)
print('SOURCES.md scrubbed; manifest link points at sources_manifest_public.csv')
